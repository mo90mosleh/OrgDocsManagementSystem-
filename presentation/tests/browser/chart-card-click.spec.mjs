import{test,expect}from'@playwright/test';import{backend}from'./pages-backend.mjs';
test.skip(!process.env.PAGES_BASE_PATH,'Pages build only');
const currentZoom=page=>page.locator('.react-flow__viewport').evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).a);
for(const direction of ['افقی','عمودی'])for(const type of ['سمت‌های سازمانی','دپارتمان‌ها'])
test(`card opens floating KPI-first tabs without reducing chart: ${type}, ${direction}`,async({page})=>{
 await backend(page);await page.goto('./#/organization/chart');
 await page.getByRole('radio',{name:type,exact:true}).click();
 await page.getByRole('radio',{name:direction,exact:true}).click();
 const label=type==='سمت‌های سازمانی'?'مدیر فروش تهران':'فروش تهران';
 const canvas=page.locator('.interactive-chart');const initialWidth=await canvas.evaluate(e=>e.getBoundingClientRect().width);
 await page.getByLabel('یافتن واحد، سمت یا شخص در چارت').fill(label);
 await page.getByRole('region',{name:'نتایج جست‌وجوی چارت'}).getByRole('button',{name:label+(type==='سمت‌های سازمانی'?' فروش تهران':''),exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'فرآیندها و شاخص‌های مرتبط با گره انتخاب‌شده'});
 await expect(dialog).toBeVisible();
 await expect(dialog.getByRole('radiogroup',{name:'نمایش اطلاعات مرتبط'}).getByRole('radio',{name:/^شاخص‌ها/})).toHaveAttribute('aria-checked','true');
 await expect(dialog.getByRole('region',{name:'شاخص‌های مرتبط'})).toBeVisible();
 await expect(dialog.getByRole('region',{name:'فرآیندهای مرتبط'})).toHaveCount(0);
 await expect.poll(()=>canvas.evaluate(e=>e.getBoundingClientRect().width)).toBe(initialWidth);
 const card=page.getByRole('button',{name:type==='سمت‌های سازمانی'?'انتخاب سمت مدیر فروش تهران در فروش تهران':'انتخاب واحد فروش تهران',exact:true});
 await expect(card).toHaveCSS('cursor','pointer');
 await expect(card.locator('..')).toHaveCSS('cursor','pointer');
 await expect(page.locator('.node-linked-trigger')).toHaveCount(0);
 await dialog.getByRole('radio',{name:/^فرآیندها/}).click();
 await expect(dialog.getByRole('region',{name:'فرآیندهای مرتبط'})).toBeVisible();
 await expect(dialog.getByRole('region',{name:'شاخص‌های مرتبط'})).toHaveCount(0);
 await dialog.getByRole('button',{name:'بستن اطلاعات مرتبط'}).click();
 await expect(dialog).toHaveCount(0);
 const z=await currentZoom(page);await card.click();
 await expect(dialog).toBeVisible();
 await expect(dialog.getByRole('radio',{name:/^شاخص‌ها/})).toHaveAttribute('aria-checked','true');
 await expect.poll(()=>currentZoom(page)).toBe(z);
 await expect.poll(()=>canvas.evaluate(e=>e.getBoundingClientRect().width)).toBe(initialWidth);
 await dialog.getByRole('button',{name:'بستن اطلاعات مرتبط'}).click();
 const toggle=card.locator('..').getByRole('button',{name:/جمع کردن .*فروش تهران/});
 await toggle.hover();await expect(card.locator('..').locator('.chart-node-preview')).toBeVisible();
 await toggle.click();await expect(card.locator('..').getByRole('button',{name:/باز کردن .*فروش تهران/})).toHaveAttribute('aria-expanded','false');
});
